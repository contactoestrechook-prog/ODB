-- NOTA DE PEDIDO SIN PROVEEDOR (Leandro, 10/11/2026): «necesito que tenga una
-- función compras que pueda hacer una nota de pedido sin proveedor asignado y
-- que después le podamos asignar el proveedor o simplemente exportarla así».
-- El caso: Don Satur figura en la lista de Clan pero a veces se le compra a
-- Distri Sur; el pedido se arma primero con lo que hace falta y el proveedor
-- se decide después. Cada renglón puede ir a un proveedor distinto: al
-- asignarlo se crea la orden de compra de siempre (a aprobación del dueño) y
-- el renglón queda marcado con ese proveedor y el número de orden.
create table if not exists public.notas_pedido (
  id uuid primary key default gen_random_uuid(),
  numero integer generated by default as identity unique,
  titulo text,
  sucursal_id uuid not null references public.sucursales(id),
  -- [{ sku, nombre, cantidad, proveedorId?, proveedor?, ordenCompraId?, ordenNumero? }]
  renglones jsonb not null default '[]'::jsonb,
  estado text not null default 'abierta' check (estado in ('abierta', 'cerrada', 'anulada')),
  creada_por uuid references public.usuarios(id) on delete set null,
  creada_en timestamptz not null default now(),
  actualizada_por uuid references public.usuarios(id) on delete set null,
  actualizada_en timestamptz not null default now()
);
create index if not exists notas_pedido_estado_idx on public.notas_pedido (estado, actualizada_en desc);

-- solo la API (clave de servicio) la lee y escribe
alter table public.notas_pedido enable row level security;
revoke all on public.notas_pedido from anon, authenticated;
